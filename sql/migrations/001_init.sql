-- Gymnasium Smart Reminder & Follow-up : skema awal (PostgreSQL / Supabase)
-- Semua waktu disimpan sebagai TIMESTAMP tanpa zona (waktu lokal WIB), konsisten dengan data synthetic.
-- Jalankan di Supabase SQL Editor.

BEGIN;

CREATE TABLE IF NOT EXISTS customers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama        TEXT        NOT NULL,
    no_whatsapp TEXT        NOT NULL UNIQUE,
    persona     TEXT        NOT NULL CHECK (persona IN ('ibu-ibu', 'lansia', 'menengah_atas')),
    catatan     TEXT,
    join_date   DATE        NOT NULL,
    created_at  TIMESTAMP   NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS schedules (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_kelas  TEXT        NOT NULL,
    tipe        TEXT        NOT NULL CHECK (tipe IN ('group_class', 'private')),
    waktu_mulai TIMESTAMP   NOT NULL,
    pelatih     TEXT        NOT NULL,
    kapasitas   INTEGER     NOT NULL CHECK (kapasitas > 0),
    created_at  TIMESTAMP   NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS attendance (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT      NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    schedule_id BIGINT      NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
    status      TEXT        NOT NULL CHECK (status IN ('hadir', 'tidak_hadir', 'reschedule')),
    created_at  TIMESTAMP   NOT NULL DEFAULT now(),
    UNIQUE (customer_id, schedule_id)
);

CREATE TABLE IF NOT EXISTS reschedules (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      BIGINT    NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    schedule_id_asal BIGINT    NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
    schedule_id_baru BIGINT    REFERENCES schedules(id) ON DELETE SET NULL,
    alasan           TEXT,
    created_at       TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reminders (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id            BIGINT    NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    schedule_id            BIGINT    REFERENCES schedules(id) ON DELETE SET NULL,
    status                 TEXT      NOT NULL DEFAULT 'Scheduled'
                           CHECK (status IN ('Scheduled', 'Sent', 'Responded', 'No Response')),
    priority               TEXT      CHECK (priority IN ('Low', 'Medium', 'High')),
    priority_probabilities JSONB,
    message_type           TEXT      NOT NULL DEFAULT 'reminder_kelas'
                           CHECK (message_type IN ('reminder_kelas', 'follow_up_absen', 'follow_up_tidak_merespons')),
    draft_message          TEXT,
    draft_source           TEXT      CHECK (draft_source IN ('gemini', 'template_fallback')),
    final_message          TEXT,
    created_at             TIMESTAMP NOT NULL DEFAULT now(),
    sent_at                TIMESTAMP,
    responded_at           TIMESTAMP,
    updated_at             TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reminder_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reminder_id BIGINT    NOT NULL REFERENCES reminders(id) ON DELETE CASCADE,
    from_status TEXT      CHECK (from_status IN ('Scheduled', 'Sent', 'Responded', 'No Response')),
    to_status   TEXT      NOT NULL CHECK (to_status IN ('Scheduled', 'Sent', 'Responded', 'No Response')),
    changed_at  TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS predictions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   BIGINT    NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    priority      TEXT      NOT NULL CHECK (priority IN ('Low', 'Medium', 'High')),
    probabilities JSONB     NOT NULL,
    top_factors   JSONB,
    model_version TEXT      NOT NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT now()
);

-- Index
CREATE INDEX IF NOT EXISTS idx_schedules_waktu_mulai   ON schedules (waktu_mulai);
CREATE INDEX IF NOT EXISTS idx_attendance_customer     ON attendance (customer_id);
CREATE INDEX IF NOT EXISTS idx_attendance_schedule     ON attendance (schedule_id);
CREATE INDEX IF NOT EXISTS idx_reschedules_customer    ON reschedules (customer_id);
CREATE INDEX IF NOT EXISTS idx_reminders_customer      ON reminders (customer_id);
CREATE INDEX IF NOT EXISTS idx_reminders_schedule      ON reminders (schedule_id);
CREATE INDEX IF NOT EXISTS idx_reminders_status        ON reminders (status);
CREATE INDEX IF NOT EXISTS idx_reminders_priority      ON reminders (priority);
CREATE INDEX IF NOT EXISTS idx_status_history_reminder ON reminder_status_history (reminder_id);
CREATE INDEX IF NOT EXISTS idx_predictions_customer    ON predictions (customer_id, created_at DESC);

COMMIT;
